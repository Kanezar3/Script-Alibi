import type {
  CaseOutcome,
  NormalizedProofBundle,
  ProofCaseRecord,
} from '../types/scriptAlibi';

export const STUDIONET_CHAIN_ID = 61999;
export const STUDIONET_RPC_URL = 'https://studio.genlayer.com/api';
export const STUDIONET_EXPLORER_URL = 'https://explorer-studio.genlayer.com';

export function buildExplorerTxUrl(txHash: string, baseUrl = STUDIONET_EXPLORER_URL): string {
  if (!txHash) return baseUrl;
  return `${baseUrl.replace(/\/$/, '')}/tx/${txHash}`;
}

export function buildExplorerAddressUrl(
  address: string,
  baseUrl = STUDIONET_EXPLORER_URL
): string {
  if (!address) return baseUrl;
  return `${baseUrl.replace(/\/$/, '')}/address/${address}`;
}

function inferOutcome(raw: Record<string, unknown>, index: number): CaseOutcome {
  const combined = `${raw.outcome ?? ''} ${raw.verdict ?? ''} ${raw.validity ?? ''} ${
    raw.case_id ?? raw.id ?? ''
  } ${raw.title ?? ''} ${raw.label ?? ''} ${raw.category ?? ''}`.toUpperCase();

  if (combined.includes('INJECTION') || combined.includes('ADVERSARIAL')) {
    return 'PROMPT_INJECTION_DEFENSE';
  }
  if (combined.includes('TOO_VAGUE')) return 'TOO_VAGUE';
  if (combined.includes('ORIGIN_VERIFIED')) return 'ORIGIN_VERIFIED';
  if (combined.includes('CONTRADICTED')) return 'CONTRADICTED_BY_SOURCE';
  if (combined.includes('INSUFFICIENT')) return 'INSUFFICIENT_EVIDENCE';
  if (combined.includes('CLEARABLE')) return 'CLEARABLE';

  const fallbackOrder: CaseOutcome[] = [
    'TOO_VAGUE',
    'CLEARABLE',
    'ORIGIN_VERIFIED',
    'CONTRADICTED_BY_SOURCE',
    'INSUFFICIENT_EVIDENCE',
    'PROMPT_INJECTION_DEFENSE',
  ];
  return fallbackOrder[index] ?? 'ORIGIN_VERIFIED';
}

function asString(v: unknown): string | undefined {
  if (typeof v === 'string' && v.length > 0) return v;
  if (typeof v === 'number') return String(v);
  return undefined;
}

function asNumber(v: unknown): number | null {
  if (typeof v === 'number' && Number.isFinite(v)) return v;
  if (typeof v === 'string' && v.trim() !== '' && !Number.isNaN(Number(v))) {
    return Number(v);
  }
  return null;
}

/**
 * Normalizes deploy/proof.json generated by deploy_and_seed.py
 * into a strict, predictable shape for the UI.
 */
export function normalizeProofBundle(rawInput: unknown): NormalizedProofBundle {
  const raw = (rawInput && typeof rawInput === 'object' ? rawInput : {}) as Record<
    string,
    unknown
  >;

  const networkObj =
    raw.network && typeof raw.network === 'object'
      ? (raw.network as Record<string, unknown>)
      : undefined;

  const contractAddress =
    asString(raw.contract_address) ??
    asString(raw.contractAddress) ??
    asString((raw.contract as Record<string, unknown> | undefined)?.address) ??
    '';

  const explorerBaseUrl =
    asString(networkObj?.explorer_url) ??
    asString(raw.explorer_base_url) ??
    asString(raw.explorerUrl) ??
    STUDIONET_EXPLORER_URL;

  const isPlaceholder = Boolean(raw._placeholder) || !contractAddress;

  const poolsArr = Array.isArray(raw.pools) ? (raw.pools as Record<string, unknown>[]) : [];
  const claimsArr = Array.isArray(raw.claims) ? (raw.claims as Record<string, unknown>[]) : [];

  const rawCasesSource = Array.isArray(raw.cases)
    ? raw.cases
    : Array.isArray(raw.transactions)
      ? raw.transactions
      : raw.cases && typeof raw.cases === 'object'
        ? Object.entries(raw.cases as Record<string, unknown>).map(([key, val]) => ({
            case_id: key,
            ...(typeof val === 'object' && val !== null ? val : {}),
          }))
        : [];

  const cases: ProofCaseRecord[] = rawCasesSource.map((entry, idx) => {
    const item = (entry && typeof entry === 'object' ? entry : {}) as Record<
      string,
      unknown
    >;
    const input = ((item.inputs && typeof item.inputs === 'object'
      ? item.inputs
      : item.input && typeof item.input === 'object'
        ? item.input
        : {}) as Record<string, unknown>);
    const output = (item.output && typeof item.output === 'object' ? item.output : {}) as Record<
      string,
      unknown
    >;
    const result = (item.result && typeof item.result === 'object' ? item.result : {}) as Record<
      string,
      unknown
    >;

    const poolId = asNumber(item.pool_id ?? input.pool_id ?? output.pool_id ?? result.pool_id);
    const claimId = asNumber(item.claim_id ?? output.claim_id ?? result.claim_id);

    const matchingPool =
      poolId && poolId > 0
        ? poolsArr.find((p) => Number(p.pool_id) === poolId)
        : undefined;
    const matchingClaim =
      claimId && claimId > 0
        ? claimsArr.find((c) => Number(c.claim_id) === claimId)
        : undefined;

    const txHash =
      asString(item.tx_hash) ??
      asString(item.txHash) ??
      asString(item.hash) ??
      '';

    const outcome = inferOutcome(item, idx);
    const rawVerdict =
      asString(item.outcome) ??
      asString(item.verdict) ??
      asString(item.validity) ??
      asString(output.verdict) ??
      asString(output.validity) ??
      asString(result.verdict) ??
      asString(result.validity) ??
      outcome;

    let economicEffect =
      asString(item.economic_effect) ??
      asString(item.settlement) ??
      asString(item.payout_note);

    if (!economicEffect) {
      if (outcome === 'TOO_VAGUE') {
        const credited = asString(item.credited_refundable_wei) ?? asString(input.bounty_wei);
        economicEffect = credited
          ? `Deposit (${credited} wei) credited to sender's refundable_balances (zero stranded funds).`
          : "Deposit credited to sender's refundable_balances.";
      } else if (outcome === 'CLEARABLE') {
        const bounty = asString(input.bounty_wei) ?? asString(matchingPool?.bounty_wei);
        economicEffect = bounty
          ? `Clause SHA-256 frozen on-chain; pool opened with ${bounty} wei bounty locked.`
          : 'Clause SHA-256 frozen on-chain; pool opened.';
      } else if (outcome === 'ORIGIN_VERIFIED') {
        const payout = asString(matchingClaim?.payout_wei);
        economicEffect = payout
          ? `Pool marked CLEARED_VERIFIED; stake + bounty (${payout} wei) credited to claimant refundable_balances.`
          : 'Pool marked CLEARED_VERIFIED; stake + bounty credited to claimant.';
      } else if (outcome === 'CONTRADICTED_BY_SOURCE') {
        const payout = asString(matchingClaim?.payout_wei);
        economicEffect = payout
          ? `Pool marked HAZARD_CONTRADICTED; stake + bounty (${payout} wei) credited to claimant refundable_balances.`
          : 'Pool marked HAZARD_CONTRADICTED; stake + bounty credited to claimant.';
      } else if (outcome === 'INSUFFICIENT_EVIDENCE' || outcome === 'PROMPT_INJECTION_DEFENSE') {
        const stake = asString(input.stake_wei) ?? asString(matchingClaim?.stake_wei);
        economicEffect = stake
          ? `Claim DISMISSED_INSUFFICIENT; pool remains OPEN; claimant stake (${stake} wei) forfeited to pool creator's refundable_balances.`
          : 'Claim DISMISSED_INSUFFICIENT; pool remains OPEN; stake forfeited to pool creator.';
      }
    }

    return {
      caseId: asString(item.case_id) ?? asString(item.id) ?? `case-${idx + 1}`,
      caseNumber: asNumber(item.case_number) ?? idx + 1,
      title:
        asString(item.title) ??
        asString(item.label) ??
        asString(item.name) ??
        `Case ${idx + 1}: ${outcome}`,
      subtitle:
        asString(item.description) ??
        asString(item.subtitle) ??
        asString(item.scenario) ??
        '',
      outcome,
      rawVerdict,
      action:
        asString(item.action) ??
        asString(item.method) ??
        asString(item.function_name) ??
        (outcome === 'TOO_VAGUE' || outcome === 'CLEARABLE'
          ? 'create_clearance_pool'
          : 'submit_alibi_claim'),
      txHash,
      blockNumber: asNumber(item.block_number) ?? asString(item.block_number) ?? null,
      finalityStatus:
        asString(item.finality_status) ??
        asString(item.status) ??
        asString(item.status_name) ??
        'FINALIZED',
      executionResult:
        asString(item.execution_result) ??
        asString(item.tx_execution_result) ??
        asString(item.executionResultName),
      appealWindowNote: asString(item.appeal_window) ?? asString(item.appeal_note),
      poolId,
      claimId,
      workTitle:
        asString(item.work_title ?? input.work_title) ??
        asString(matchingPool?.work_title),
      elementClause:
        asString(item.element_clause ?? input.element_clause) ??
        asString(matchingPool?.element_clause),
      clauseSha256:
        asString(item.clause_sha256 ?? output.clause_sha256 ?? result.clause_sha256) ??
        asString(matchingPool?.clause_sha256),
      evidenceUrl: asString(item.evidence_url ?? input.evidence_url ?? matchingClaim?.evidence_url),
      startLine: asNumber(item.start_line ?? input.start_line ?? matchingClaim?.start_line),
      endLine: asNumber(item.end_line ?? input.end_line ?? matchingClaim?.end_line),
      snippetSha256: asString(
        item.snippet_sha256 ??
          output.snippet_sha256 ??
          result.snippet_sha256 ??
          matchingClaim?.snippet_sha256
      ),
      snippetText: asString(
        item.snippet_excerpt ??
          item.snippet_text ??
          item.snippet ??
          output.snippet ??
          matchingClaim?.snippet_excerpt
      ),
      evidenceQuote: asString(
        item.evidence_quote ??
          output.evidence_quote ??
          result.evidence_quote ??
          matchingClaim?.evidence_quote
      ),
      rationale: asString(
        item.rationale ?? output.rationale ?? result.rationale ?? matchingClaim?.rationale
      ),
      economicEffect,
      explorerTxUrl:
        asString(item.explorer_url) ??
        asString(item.explorer_tx_url) ??
        (txHash ? buildExplorerTxUrl(txHash, explorerBaseUrl) : undefined),
    };
  });

  return {
    isPlaceholder,
    network:
      asString(networkObj?.name) ??
      (typeof raw.network === 'string' ? raw.network : undefined) ??
      'GenLayer StudioNet',
    chainId:
      asNumber(networkObj?.chain_id ?? raw.chain_id ?? raw.chainId) ?? STUDIONET_CHAIN_ID,
    rpcUrl:
      asString(networkObj?.rpc_url ?? raw.rpc_url ?? raw.rpcUrl) ?? STUDIONET_RPC_URL,
    explorerBaseUrl,
    contractAddress,
    deployerAddress:
      asString(raw.deployer_address ?? raw.deployer) ?? '',
    runnerHash: asString(raw.runner_hash ?? raw.genvm_runner_hash),
    contractSha256: asString(
      raw.contract_source_sha256 ?? raw.contract_sha256 ?? raw.source_sha256
    ),
    generatedAt: asString(raw.generated_at_utc ?? raw.generated_at ?? raw.timestamp),
    cases,
    rawProof: raw,
  };
}
